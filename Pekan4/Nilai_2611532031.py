Nilai_2031 = int(input("Inputkan Nilai Angka= "))

if Nilai_2031 >= 81:
    print("A")
elif Nilai_2031 >= 70:
    print("B")
elif Nilai_2031 >= 60:
    print("C")
elif Nilai_2031 >= 50:
    print("D")
else:
    print("E")